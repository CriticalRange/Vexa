def exports(real):
    out = subprocess.check_output([NM, "-D", "--defined-only", real], text=True)
    names = {
        line.split()[-1].split("@")[0]
        for line in out.splitlines()
        if line.split() and len(line.split()) >= 3 and line.split()[1] in "TtWw"
    }
    return sorted(names)


